import fs from 'node:fs/promises';
import path from 'node:path';

const root = process.cwd();
const nodeModules = path.join(root, 'node_modules');
const entries = [];
async function collect(directory) {
  let children = [];
  try { children = await fs.readdir(directory, { withFileTypes: true }); } catch { return; }
  for (const child of children) {
    if (!child.isDirectory() || child.name === '.bin') continue;
    const target = path.join(directory, child.name);
    if (child.name.startsWith('@')) { await collect(target); continue; }
    try {
      const pkg = JSON.parse(await fs.readFile(path.join(target, 'package.json'), 'utf8'));
      if (pkg.name && pkg.version) entries.push({ name: pkg.name, version: pkg.version, license: pkg.license || 'License not declared in package metadata' });
    } catch { /* Nested folders without a package manifest are not packages. */ }
    await collect(path.join(target, 'node_modules'));
  }
}
await collect(nodeModules);
const runnerLib = path.join(root, 'dmn-runner', 'dist', 'lib');
let runnerJars = [];
try { runnerJars = (await fs.readdir(runnerLib)).filter(file => file.endsWith('.jar')).sort(); } catch { runnerJars = ['The DMN runner has not been built yet.']; }
const nodeRows = [...new Map(entries.map(entry => [`${entry.name}@${entry.version}`, entry])).values()].sort((a, b) => a.name.localeCompare(b.name));
const lines = ['# Third-party notices', '', 'Generated by `npm run notices:generate`. This inventory accompanies BPM Modeler releases. License and NOTICE files embedded in the bundled Java JARs and runtime must remain distributed unchanged.', '', '## Node.js packages', '', '| Package | Version | Declared license |', '| --- | --- | --- |', ...nodeRows.map(entry => `| ${entry.name} | ${entry.version} | ${typeof entry.license === 'string' ? entry.license : JSON.stringify(entry.license)} |`), '', '## Bundled DMN runner JARs', '', ...runnerJars.map(file => `- ${file}`), ''];
await fs.writeFile(path.join(root, 'THIRD-PARTY-NOTICES.md'), lines.join('\n'), 'utf8');
